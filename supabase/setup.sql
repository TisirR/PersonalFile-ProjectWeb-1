-- 可公开读取主页数据
drop policy if exists "public read profile" on public.site_profile;
create policy "public read profile"
on public.site_profile for select
using (true);

drop policy if exists "public read appearance" on public.site_appearance;
create policy "public read appearance"
on public.site_appearance for select
using (true);

drop policy if exists "public read cards" on public.info_cards;
create policy "public read cards"
on public.info_cards for select
using (true);

-- 已登录的 Supabase Auth 用户可以修改网站内容
drop policy if exists "authenticated manage profile" on public.site_profile;
create policy "authenticated manage profile"
on public.site_profile for all to authenticated
using (true) with check (true);

drop policy if exists "authenticated manage appearance" on public.site_appearance;
create policy "authenticated manage appearance"
on public.site_appearance for all to authenticated
using (true) with check (true);

drop policy if exists "authenticated manage cards" on public.info_cards;
create policy "authenticated manage cards"
on public.info_cards for all to authenticated
using (true) with check (true);

-- 访客统计：允许匿名读、插入、更新自己的 visitor_id。
-- 这是静态 GitHub Pages 下的基础方案，不适合作为严格防刷统计。
drop policy if exists "public read visitors" on public.visitor_sessions;
create policy "public read visitors"
on public.visitor_sessions for select
using (true);

drop policy if exists "public insert visitors" on public.visitor_sessions;
create policy "public insert visitors"
on public.visitor_sessions for insert
with check (true);

drop policy if exists "public update visitors" on public.visitor_sessions;
create policy "public update visitors"
on public.visitor_sessions for update
using (true) with check (true);

-- 图片存储桶
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values (
    'site-images',
    'site-images',
    true,
    10485760,
    array['image/jpeg','image/png','image/webp','image/gif','image/avif']
)
on conflict (id) do update
set public = true,
    file_size_limit = 10485760;

drop policy if exists "public read site images" on storage.objects;
create policy "public read site images"
on storage.objects for select
using (bucket_id = 'site-images');

drop policy if exists "authenticated upload site images" on storage.objects;
create policy "authenticated upload site images"
on storage.objects for insert to authenticated
with check (bucket_id = 'site-images');

drop policy if exists "authenticated update site images" on storage.objects;
create policy "authenticated update site images"
on storage.objects for update to authenticated
using (bucket_id = 'site-images')
with check (bucket_id = 'site-images');

drop policy if exists "authenticated delete site images" on storage.objects;
create policy "authenticated delete site images"
on storage.objects for delete to authenticated
using (bucket_id = 'site-images');

