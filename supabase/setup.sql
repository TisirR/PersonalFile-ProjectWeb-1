create table if not exists public.site_profile (
    id bigint primary key default 1,
    display_name text,
    tagline text,
    introduction text,
    avatar_url text,
    active_title text,
    inactive_title text
);

create table if not exists public.site_appearance (
    id bigint primary key default 1,
    background_type text default 'default',
    solid_color text default '#6d5dfc',
    gradient_start text default '#667eea',
    gradient_end text default '#764ba2',
    gradient_direction text default '135deg',
    background_image_url text,
    background_blur integer default 0,
    background_brightness integer default 100
);

create table if not exists public.info_cards (
    id bigint generated by default as identity primary key,
    title text not null default 'Untitled',
    content text default '',
    position text not null default 'center'
        check (position in ('left','center','right')),
    display_style text not null default 'normal'
        check (display_style in ('normal','connected')),
    group_id text,
    sort_order integer default 0
);

create table if not exists public.visitor_sessions (
    visitor_id text primary key,
    first_seen_at timestamptz not null default now(),
    last_seen_at timestamptz not null default now()
);

